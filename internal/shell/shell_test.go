func TestLauncherScriptGolden(t *testing.T) {
	got, err := LauncherScript("claude", "CLAUDE_CONFIG_DIR", "/home/x/.claude-work")
	if err != nil {
		t.Fatalf("LauncherScript: %v", err)
	}
	want := "#!/bin/sh\n# generated by aiacc — do not edit; re-run `aiacc setup`\n" +
		"exec env CLAUDE_CONFIG_DIR='/home/x/.claude-work' claude \"$@\"\n"
	if got != want {
		t.Errorf("LauncherScript =\n%q\nwant\n%q", got, want)
	}
}

func TestLauncherScriptRejectsBadInput(t *testing.T) {
	if _, err := LauncherScript("cla ude", "CLAUDE_CONFIG_DIR", "/x"); err == nil {
		t.Fatal("want error for bad command")
	}
	if _, err := LauncherScript("claude", "BAD VAR", "/x"); err == nil {
		t.Fatal("want error for bad env var")
	}
	if _, err := LauncherScript("claude", "CLAUDE_CONFIG_DIR", "/x\nb"); !errors.Is(err, ErrUnsafeDir) {
		t.Fatalf("want ErrUnsafeDir, got %v", err)
	}
}

// TestLauncherScriptNoBreakout runs the generated script with a hostile dir and
// proves the value reaches the launched command intact, with nothing injected.
func TestLauncherScriptNoBreakout(t *testing.T) {
	sh, err := exec.LookPath("sh")
	if err != nil {
		t.Skip("sh not available")
	}
	tmp := t.TempDir()
	marker := filepath.Join(tmp, "INJECTED")
	dir := `/tmp/a'; touch ` + marker + `; echo '`
	// Use `env` itself as the "command": it prints the environment, so we can read
	// back exactly what CLAUDE_CONFIG_DIR was set to.
	script, err := LauncherScript("env", "CLAUDE_CONFIG_DIR", dir)
	if err != nil {
		t.Fatalf("LauncherScript: %v", err)
	}
	out, err := exec.Command(sh, "-c", script).CombinedOutput()
	if err != nil {
		t.Fatalf("running script failed: %v (%s)", err, out)
	}
	if _, statErr := os.Stat(marker); statErr == nil {
		t.Fatal("breakout: injected command ran")
	}
	if !strings.Contains(string(out), "CLAUDE_CONFIG_DIR="+dir) {
		t.Fatalf("env var not passed intact:\n%s", out)
	}
}

func TestPathLine(t *testing.T) {
	cases := map[string]string{
		"bash": `export PATH='/home/x/.local/bin':"$PATH"`,
		"zsh":  `export PATH='/home/x/.local/bin':"$PATH"`,
		"fish": `fish_add_path '/home/x/.local/bin'`,
	}
	for sh, want := range cases {
		got, err := PathLine(sh, "/home/x/.local/bin")
		if err != nil {
			t.Fatalf("PathLine(%s): %v", sh, err)
		}
		if got != want {
			t.Errorf("PathLine(%s) = %q, want %q", sh, got, want)
		}
	}
}

// An account's settings file reaches the CLI ahead of the user's own args, and
// a launcher with no args stays byte-identical to one written before args existed.
func TestLauncherScriptArgsGolden(t *testing.T) {
	got, err := LauncherScript("claude", "CLAUDE_CONFIG_DIR", "/home/x/.claude-glm", "--settings", "/home/x/glm.json")
	if err != nil {
		t.Fatalf("LauncherScript: %v", err)
	}
	want := "#!/bin/sh\n# generated by aiacc — do not edit; re-run `aiacc setup`\n" +
		"exec env CLAUDE_CONFIG_DIR='/home/x/.claude-glm' claude '--settings' '/home/x/glm.json' \"$@\"\n"
	if got != want {
		t.Errorf("LauncherScript =\n%q\nwant\n%q", got, want)
	}
	if _, err := LauncherScript("claude", "CLAUDE_CONFIG_DIR", "/x", "a\nb"); !errors.Is(err, ErrUnsafeDir) {
		t.Fatalf("a control char in an arg must be refused, got %v", err)
	}
}

// A hostile settings path is passed as one literal argument, never run.
func TestLauncherScriptArgNoBreakout(t *testing.T) {
	sh, err := exec.LookPath("sh")
	if err != nil {
		t.Skip("sh not available")
	}
	marker := filepath.Join(t.TempDir(), "INJECTED")
	arg := `/tmp/a'; touch ` + marker + `; echo '`
	script, err := LauncherScript("echo", "CLAUDE_CONFIG_DIR", "/x", arg)
	if err != nil {
		t.Fatalf("LauncherScript: %v", err)
	}
	out, err := exec.Command(sh, "-c", script).CombinedOutput()
	if err != nil {
		t.Fatalf("running script failed: %v (%s)", err, out)
	}
	if _, statErr := os.Stat(marker); statErr == nil {
		t.Fatal("breakout: injected command ran")
	}
	if strings.TrimSpace(string(out)) != arg {
		t.Fatalf("arg not passed intact: %q", out)
	}
}

// pathLineBreakout runs the PathLine statement for dir in shellBin and reports
// whether the injected command ran. The shell gets no startup files and a temp
// HOME, so fish_add_path cannot touch the user's config.
func pathLineBreakout(t *testing.T, shellBin, shellName, dir string, args ...string) bool {
	t.Helper()
	marker := filepath.Join(t.TempDir(), "INJECTED")
	line, err := PathLine(shellName, strings.ReplaceAll(dir, "MARKER", marker))
	if err != nil {
		t.Fatalf("PathLine(%s): %v", shellName, err)
	}
	home := t.TempDir()
	cmd := exec.Command(shellBin, append(args, "-c", line)...)
	cmd.Env = append(os.Environ(), "HOME="+home, "XDG_CONFIG_HOME="+home, "XDG_DATA_HOME="+home)
	_, _ = cmd.CombinedOutput() // a failing PATH line is fine; only an injected command matters
	_, statErr := os.Stat(marker)
	return statErr == nil
}

// TestPathLineNoBreakoutBash: PosixQuote keeps a hostile directory inside its
// single quotes when the PATH line is run by bash.
func TestPathLineNoBreakoutBash(t *testing.T) {
	bash, err := exec.LookPath("bash")
	if err != nil {
		t.Skip("bash not available")
	}
	dir := `/tmp/a'; /usr/bin/touch MARKER; echo '`
	if pathLineBreakout(t, bash, "bash", dir, "--norc", "--noprofile") {
		t.Fatal("breakout: injected command ran while running the bash PATH line")
	}
}

// TestPathLineNoBreakoutFish: fishSingleQuote doubles a trailing backslash before
// a quote. Without that, the backslash escapes the closing quote in fish.
func TestPathLineNoBreakoutFish(t *testing.T) {
	fish, err := exec.LookPath("fish")
	if err != nil {
		t.Skip("fish not available")
	}
	dir := `/tmp/a\'; touch MARKER; echo \'`
	if pathLineBreakout(t, fish, "fish", dir, "--no-config") {
		t.Fatal("breakout: injected command ran while running the fish PATH line")
	}
}
