// Package shell builds the per-profile launcher scripts that `aiacc setup`
// installs onto PATH. Each script runs the provider's CLI with the profile's
// config directory selected via an environment variable — e.g. `claude-work`
// runs `CLAUDE_CONFIG_DIR=<dir> claude`.
//
// The directory value is embedded in a script the shell executes, so it is the
// injection surface: directory values and identifiers are validated and
// single-quote escaped here before they reach a shell.
package shell

import (
	"errors"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	// ErrUnknownShell is returned for a shell aiacc does not support.
	ErrUnknownShell = errors.New("unknown shell")
	// ErrUnsafeDir is returned when the directory is empty or contains a control
	// character that could corrupt or escape the emitted statement.
	ErrUnsafeDir = errors.New("unsafe directory value")
)

var (
	// envVarRe matches a POSIX shell identifier.
	envVarRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	// cmdRe matches a bare command token (no spaces or shell metacharacters).
	cmdRe = regexp.MustCompile(`^[A-Za-z0-9_.+-]+$`)
)

// RcPath is the conventional startup file for a shell, absolute. It does not
// check whether the file exists — callers create it on write.
func RcPath(shellName string) (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	switch shellName {
	case "bash":
		return filepath.Join(home, ".bashrc"), nil
	case "zsh":
		return filepath.Join(home, ".zshrc"), nil
	case "fish":
		return filepath.Join(home, ".config", "fish", "config.fish"), nil
	default:
		return "", ErrUnknownShell
	}
}

// LauncherMark is the comment every generated launcher carries. `aiacc doctor`
// uses it to tell a launcher aiacc wrote from an unrelated command that happens
// to share the name, so it never reports on — or blames — a file that isn't ours.
const LauncherMark = "# generated by aiacc"

// IsLauncher reports whether body is a launcher LauncherScript wrote: the
// shebang on line 1 and the mark opening line 2. The mark appearing anywhere
// else, as in someone's script that quotes it, does not make a file ours.
func IsLauncher(body string) bool {
	lines := strings.SplitN(body, "\n", 3)
	return len(lines) >= 2 && lines[0] == "#!/bin/sh" && strings.HasPrefix(lines[1], LauncherMark)
}

// LauncherScript returns an executable POSIX-sh script that launches command
// with envVar pointed at dir — the on-PATH launcher aiacc installs, so a command
// like `claude-work` works in any shell with no sourcing or reload. dir and args
// are single-quote escaped so a hostile value can't break out; args go to the
// command ahead of the user's own.
func LauncherScript(command, envVar, dir string, args ...string) (string, error) {
	if !cmdRe.MatchString(command) || !envVarRe.MatchString(envVar) {
		return "", ErrUnknownShell
	}
	if err := validateDir(dir); err != nil {
		return "", err
	}
	if err := validateArgs(args); err != nil {
		return "", err
	}
	return "#!/bin/sh\n" +
		LauncherMark + " — do not edit; re-run `aiacc setup`\n" +
		"exec env " + envVar + "=" + PosixQuote(dir) + " " + command +
		quoted(args, PosixQuote) + " \"$@\"\n", nil
}

// quoted renders args as space-prefixed quoted words, "" when there are none —
// so a launcher without args is byte-identical to one written before args.
func quoted(args []string, quote func(string) string) string {
	var b strings.Builder
	for _, a := range args {
		b.WriteString(" " + quote(a))
	}
	return b.String()
}

// PathLine is the line that adds dir to PATH in a shell startup file, used only
// as a fallback when no writable directory is already on PATH.
func PathLine(shellName, dir string) (string, error) {
	switch shellName {
	case "fish":
		return "fish_add_path " + fishSingleQuote(dir), nil
	case "bash", "zsh":
		return "export PATH=" + PosixQuote(dir) + `:"$PATH"`, nil
	default:
		return "", ErrUnknownShell
	}
}

// validateArgs applies validateDir's rule to each launcher argument.
func validateArgs(args []string) error {
	for _, a := range args {
		if err := validateDir(a); err != nil {
			return err
		}
	}
	return nil
}

// validateDir rejects empty input and any byte below 0x20 (control characters),
// which are unsafe for a sourced statement.
func validateDir(dir string) error {
	if dir == "" {
		return ErrUnsafeDir
	}
	for i := 0; i < len(dir); i++ {
		if dir[i] < 0x20 {
			return ErrUnsafeDir
		}
	}
	return nil
}

// PosixQuote wraps s in single quotes for bash/zsh (fish reads the same idiom),
// replacing each embedded single quote with the close-quote / escaped-quote /
// reopen-quote idiom. Exported for printed shell commands like handoff's resume
// line, which the user is told to paste into a shell.
// Backslashes are literal inside POSIX single quotes, so the quote is the only
// character that needs handling.
func PosixQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// fishSingleQuote wraps s in single quotes for fish. fish treats backslash as an
// escape inside single quotes, so backslashes are doubled first; otherwise a
// value ending in a backslash could escape the quoting. Then single quotes are
// escaped as \'.
func fishSingleQuote(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, "'", `\'`)
	return "'" + s + "'"
}
