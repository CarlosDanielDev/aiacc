const foreignBody = "#!/bin/sh\n# my own script, tracked in dotfiles\nexec mine \"$@\"\n"

// foreignSetup is a hermetic install with one account "work" and a file at
// binDir/work that aiacc did not write. It returns the config path and that file.
func foreignSetup(t *testing.T) (cfgPath, foreign string) {
	t.Helper()
	home := hermeticHome(t)
	cfgPath = filepath.Join(home, "aiacc", "config.toml")
	if err := saveAccount(cfgPath, "claude", "work", filepath.Join(home, ".claude-work"), 0, "", "", ""); err != nil {
		t.Fatal(err)
	}
	foreign = filepath.Join(home, ".local", "bin", "work")
	if err := os.WriteFile(foreign, []byte(foreignBody), 0o755); err != nil {
		t.Fatal(err)
	}
	return cfgPath, foreign
}

func assertForeignIntact(t *testing.T, path string) {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("foreign file is gone: %v", err)
	}
	if string(got) != foreignBody {
		t.Fatalf("foreign file was modified:\n%s", got)
	}
}

func TestSetupLeavesForeignLauncherAlone(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	res, err := doSetup(cfgPath, false)
	if err != nil {
		t.Fatal(err)
	}
	assertForeignIntact(t, foreign)
	if !slices.Contains(res.Skipped, foreign) {
		t.Fatalf("setup did not report %s as skipped: %v", foreign, res.Skipped)
	}
	if slices.Contains(res.Names, "work") {
		t.Fatalf("skipped account still listed as installed: %v", res.Names)
	}
}

func TestSetupReportNamesForeignLauncher(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	res, err := doSetup(cfgPath, false)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	writeSetupReport(&out, res)
	text := out.String()
	if !strings.Contains(text, tildeize(foreign)) {
		t.Fatalf("warning does not name %s:\n%s", tildeize(foreign), text)
	}
	if !strings.Contains(text, "aiacc setup --replace") {
		t.Fatalf("warning does not say how to resolve it:\n%s", text)
	}
}

func TestSetupReplaceBacksUpForeignLauncher(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	res, err := doSetup(cfgPath, true)
	if err != nil {
		t.Fatal(err)
	}
	bak := foreign + ".aiacc-bak"
	got, err := os.ReadFile(bak)
	if err != nil || string(got) != foreignBody {
		t.Fatalf("original not backed up to %s: %v\n%s", bak, err, got)
	}
	if !slices.Contains(res.Backups, bak) {
		t.Fatalf("setup did not report backup %s: %v", bak, res.Backups)
	}
	launcher, err := os.ReadFile(foreign)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(launcher), shell.LauncherMark) {
		t.Fatalf("takeover did not write an aiacc launcher:\n%s", launcher)
	}
}

func TestSyncLauncherRefusesForeignFile(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	err := syncLauncher(cfgPath, "claude", "work")
	if err == nil || !strings.Contains(err.Error(), tildeize(foreign)) || !strings.Contains(err.Error(), "--replace") {
		t.Fatalf("want an error naming %s and the --replace fix, got %v", tildeize(foreign), err)
	}
	assertForeignIntact(t, foreign)
}

func TestRemoveLauncherKeepsForeignFile(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	removeLauncher(cfgPath, "work")
	assertForeignIntact(t, foreign)
}

// Our own launchers stay refreshable: the guard must not turn a second setup
// into a skip.
func TestSetupRewritesOwnLauncher(t *testing.T) {
	home := hermeticHome(t)
	cfgPath := filepath.Join(home, "aiacc", "config.toml")
	if err := saveAccount(cfgPath, "claude", "work", filepath.Join(home, ".claude-work"), 0, "", "", ""); err != nil {
		t.Fatal(err)
	}
	if _, err := doSetup(cfgPath, false); err != nil {
		t.Fatal(err)
	}
	res, err := doSetup(cfgPath, false)
	if err != nil {
		t.Fatal(err)
	}
	if len(res.Skipped) != 0 || !slices.Contains(res.Names, "work") {
		t.Fatalf("own launcher not refreshed: names=%v skipped=%v", res.Names, res.Skipped)
	}
}

// A script that quotes the mark somewhere other than its header is someone
// else's: setup must not overwrite it, remove must not delete it, and doctor must
// not report it as an orphaned aiacc launcher.
func TestMarkInsideForeignScriptIsNotAiacc(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	bin := filepath.Dir(foreign)
	notes := filepath.Join(bin, "notes")
	body := "#!/bin/sh\necho 'Tip: # generated by aiacc marks launchers'\nexec mine \"$@\"\n"
	if err := os.WriteFile(notes, []byte(body), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(bin, "work"), []byte(body), 0o755); err != nil {
		t.Fatal(err)
	}
	if _, err := doSetup(cfgPath, false); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(filepath.Join(bin, "work")); string(got) != body {
		t.Fatalf("setup overwrote a script that only quotes the mark:\n%s", got)
	}
	removeLauncher(cfgPath, "work")
	if _, err := os.Stat(filepath.Join(bin, "work")); err != nil {
		t.Fatalf("remove deleted a script that only quotes the mark: %v", err)
	}
	if got := orphanLaunchers(bin, map[string]bool{}); len(got) != 0 {
		t.Fatalf("doctor reported a script that only quotes the mark as an orphan: %+v", got)
	}
}

// A symlink at the launcher path must never be written through: its target
// stays exactly as it was, with or without --replace.
func TestSetupNeverWritesThroughSymlink(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	target := filepath.Join(t.TempDir(), "precious")
	if err := os.WriteFile(target, []byte("precious"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(foreign); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(target, foreign); err != nil {
		t.Fatal(err)
	}
	if _, err := doSetup(cfgPath, false); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(target); string(got) != "precious" {
		t.Fatalf("setup wrote through the symlink to its target: %q", got)
	}
	if info, err := os.Lstat(foreign); err != nil || info.Mode()&os.ModeSymlink == 0 {
		t.Fatalf("setup without --replace changed the symlink: %v", err)
	}

	if _, err := doSetup(cfgPath, true); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(target); string(got) != "precious" {
		t.Fatalf("--replace wrote through the symlink to its target: %q", got)
	}
	bak, err := os.Readlink(foreign + ".aiacc-bak")
	if err != nil || bak != target {
		t.Fatalf("--replace did not move the symlink aside intact: target=%q err=%v", bak, err)
	}
}

// If the install fails after the original was moved aside, the error must name
// the backup, and the backup must be reported, so the user can get the original
// back by hand.
func TestReplaceInstallFailureNamesBackup(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	old := linkLauncher
	linkLauncher = func(string, string) error { return errors.New("disk full") }
	t.Cleanup(func() { linkLauncher = old })

	c, err := config.Load(cfgPath)
	if err != nil {
		t.Fatal(err)
	}
	var res tui.SetupResult
	err = writeAllLaunchers(c, filepath.Dir(foreign), true, &res)
	bak := foreign + ".aiacc-bak"
	if err == nil || !strings.Contains(err.Error(), tildeize(bak)) {
		t.Fatalf("want an error naming the backup %s, got %v", tildeize(bak), err)
	}
	if !slices.Contains(res.Backups, bak) {
		t.Fatalf("backup not reported after a failed install: %v", res.Backups)
	}
	if got, _ := os.ReadFile(bak); string(got) != foreignBody {
		t.Fatalf("original not kept at the backup: %q", got)
	}
}

// The picker cannot return a refusal (that would exit the loop), so it shows it
// on the message screen, and stays quiet for failures that already have their
// own nudge.
func TestLauncherNoticeShowsRefusal(t *testing.T) {
	cfgPath, foreign := foreignSetup(t)
	captured := captureHandoffMessage(t)
	if err := launcherNotice(syncLauncher(cfgPath, "claude", "work")); err != nil {
		t.Fatal(err)
	}
	if len(*captured) == 0 || !strings.Contains((*captured)[0].Text, tildeize(foreign)) {
		t.Fatalf("refusal not shown on the message screen: %+v", *captured)
	}
	*captured = nil
	if err := launcherNotice(nil); err != nil || len(*captured) != 0 {
		t.Fatalf("nil error should show nothing: err=%v shown=%+v", err, *captured)
	}
}

// The check and the install are separate steps. A symlink that appears in
// between must not be written through: the install replaces the link itself.
func TestInstallNeverWritesThroughSymlinkPlantedAfterCheck(t *testing.T) {
	home := hermeticHome(t)
	cfgPath := filepath.Join(home, "aiacc", "config.toml")
	if err := saveAccount(cfgPath, "claude", "work", filepath.Join(home, ".claude-work"), 0, "", "", ""); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(home, "precious")
	if err := os.WriteFile(target, []byte("precious"), 0o644); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(home, ".local", "bin", "work")
	old := installLauncher
	installLauncher = func(src, dst string) error {
		if err := os.Symlink(target, dst); err != nil {
			return err
		}
		return old(src, dst)
	}
	t.Cleanup(func() { installLauncher = old })

	if _, err := doSetup(cfgPath, false); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(target); string(got) != "precious" {
		t.Fatalf("install wrote through the symlink to its target: %q", got)
	}
	if !isAiaccLauncher(path) {
		t.Fatalf("launcher not installed over the symlink")
	}
}

// The positive side of the header match: what LauncherScript writes is ours,
// at any age, and a stale one is still ours to refresh.
func TestRealLauncherIsAiacc(t *testing.T) {
	bin := t.TempDir()
	body, err := shell.LauncherScript("claude", "CLAUDE_CONFIG_DIR", "/a/work", "--model", "x")
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(bin, "work")
	if err := os.WriteFile(path, []byte(body), 0o755); err != nil {
		t.Fatal(err)
	}
	if !isAiaccLauncher(path) || isForeign(path) {
		t.Fatalf("a launcher LauncherScript wrote is not recognised as aiacc's")
	}
	if err := os.WriteFile(path, []byte("#!/bin/sh\n"+shell.LauncherMark+" — an older build\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if !isAiaccLauncher(path) {
		t.Fatalf("an older aiacc launcher is no longer recognised")
	}
}

